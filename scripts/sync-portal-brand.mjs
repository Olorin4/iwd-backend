import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Pass the public Iron Wing website checkout with a current dist/index.html.
const website = resolve(process.argv[2]);
const portal = fileURLToPath(
    new URL("../src/onboarding/portal/", import.meta.url)
);
const site = "https://iron-wing-dispatching.com";
const markup = await readFile(resolve(website, "dist/index.html"), "utf8");
const assets = new Set();

function fragment(tag) {
    const match = markup.match(
        new RegExp(`<${tag}\\b[^>]*>[\\s\\S]*?<\\/${tag}>`)
    );
    if (!match)
        throw new Error(`Missing <${tag}> in the public homepage build`);

    return match[0]
        .replace(/href="\/(?!\/)/g, `href="${site}/`)
        .replace(/src="\/assets\/images\/([\w.-]+)"/g, (_, name) => {
            assets.add(name);
            return `src="/portal-static/iron-wing/${name}"`;
        });
}

const header = fragment("header")
    .replace(
        'class="hamburger"',
        'class="hamburger" type="button" aria-expanded="false" aria-controls="site-navigation"'
    )
    .replace(
        'class="nav-links"',
        'class="nav-links" id="site-navigation" aria-label="Iron Wing website"'
    );
const footer = fragment("footer").replace(
    /<form id="newsletter-form"[^>]*>[\s\S]*?<\/form>/,
    `<a class="secondary-cta" href="${site}/#newsletter-form">Subscribe on our website</a>`
);

const assetDir = resolve(portal, "static/iron-wing");
await mkdir(assetDir, { recursive: true });
await Promise.all([
    ...[...assets].map((name) =>
        copyFile(
            resolve(website, "src/assets/images", name),
            resolve(assetDir, name)
        )
    ),
    copyFile(
        resolve(website, "src/shared.css"),
        resolve(assetDir, "shared.css")
    ),
    writeFile(
        resolve(portal, "brand.js"),
        `// Generated by scripts/sync-portal-brand.mjs from the Iron Wing homepage.\nexport const siteHeader = ${JSON.stringify(header)};\nexport const siteFooter = ${JSON.stringify(footer)};\n`
    ),
]);
